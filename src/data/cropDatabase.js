// ── Water calculation helper
// Returns total litres/day for a given crop on a given acreage
export function calculateWaterNeeds(cropName, areaAcres) {
  const crop = CROP_DB[cropName]
  if (!crop) return null

  const hectares = areaAcres * 0.405
  const dailyMm = crop.waterMmPerSeasonTotal / 150  // spread over ~150 growing days

  return {
    dailyMmPerHa: dailyMm,
    dailyLitresPerAcre: Math.round(dailyMm * 4047), // 1 mm over 1 acre = 4047 litres
    dailyLitresTotal: Math.round(dailyMm * 4047 * areaAcres),
    weeklyLitresTotal: Math.round(dailyMm * 4047 * areaAcres * 7),
    seasonTotalLitres: Math.round(crop.waterMmPerSeasonTotal * 4047 * areaAcres),
    seasonTotalTankers: Math.round((crop.waterMmPerSeasonTotal * 4047 * areaAcres) / 5000), // 5000L tanker
  }
}

// ── Plant count helper  
export function calculatePlantCount(cropName, areaAcres) {
  const crop = CROP_DB[cropName]
  if (!crop || !crop.isSeedling) return null

  const areaSqM = areaAcres * 4047
  const plantsPerSqM = 1 / (crop.rowSpacingM * crop.plantSpacingM)
  const total = Math.round(areaSqM * plantsPerSqM)

  return {
    total,
    perAcre: Math.round(4047 / (crop.rowSpacingM * crop.plantSpacingM)),
    rowSpacingM: crop.rowSpacingM,
    plantSpacingM: crop.plantSpacingM,
    numRows: Math.round(Math.sqrt(areaSqM / crop.rowSpacingM / crop.plantSpacingM) * crop.rowSpacingM / crop.rowSpacingM),
    plantsPerRow: Math.round(Math.sqrt(areaSqM) / crop.plantSpacingM),
  }
}
